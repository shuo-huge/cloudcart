import fs from "node:fs";
import path from "node:path";

const manifestPath = path.resolve("dist/static/.vite/manifest.json");
const outputPath = path.resolve("apps/worker/src/generated/assets.ts");

if (!fs.existsSync(manifestPath)) {
  console.error("The storefront build manifest is missing. Run `pnpm build:storefront` first.");
  process.exit(1);
}

const manifest = JSON.parse(fs.readFileSync(manifestPath, "utf8"));
const entry = manifest["src/main.ts"];
if (!entry) {
  console.error("The storefront entry (src/main.ts) was not found in the Vite manifest.");
  process.exit(1);
}

const js = "/static/" + entry.file.replace(/^\/+/, "");
const css = Array.isArray(entry.css) && entry.css[0]
  ? "/static/" + entry.css[0].replace(/^\/+/, "")
  : null;

fs.mkdirSync(path.dirname(outputPath), { recursive: true });
fs.writeFileSync(
  outputPath,
  `// Generated by scripts/generate-assets.mjs. Do not edit by hand.\nexport const STOREFRONT_JS = ${JSON.stringify(js)};\nexport const STOREFRONT_CSS = ${JSON.stringify(css)};\n`,
  "utf8",
);

console.log(`Generated storefront asset references: ${js}${css ? `, ${css}` : ""}`);
